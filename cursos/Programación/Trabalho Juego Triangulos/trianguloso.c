#include <stdio.h>
#include <string.h>
#include <math.h>
#include "raylib.h"

#define N 6                      /* cantidad de triangulos del juego */
#define ARCHIVO "triangulo.txt"  /* archivo de entrada pedido en el enunciado */
#define ANCHO 800                /* tamano de la ventana */
#define ALTO 700
#define RADIO 260.0f             /* radio del hexagono dibujado */

/* ---------- Prototipos ---------- */
int     leerDatos(char *nombre, int tri[N][3]);
int     proceso(int tri[N][3], int mejorOrden[N], int mejorRot[N]);
void    salida(int tri[N][3], int orden[N], int rot[N], int puntaje);

int     ladoIzq(int tri[N][3], int t, int r);
int     ladoExt(int tri[N][3], int t, int r);
int     ladoDer(int tri[N][3], int t, int r);
int     calcularPuntaje(int tri[N][3], int orden[N], int rot[N]);
void    buscar(int tri[N][3], int pos, int usado[N], int orden[N], int rot[N],
               int *mejor, int mejorOrden[N], int mejorRot[N]);

void    armarSuma(char texto[], int tri[N][3], int orden[N], int rot[N], int puntaje);
